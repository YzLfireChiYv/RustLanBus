#![forbid(unsafe_code)]

//! Pure deterministic arrival/render simulator for RLB2 media behavior.
//!
//! Canonical source truth, network arrivals, shared render callbacks, and
//! subscription-generation controls are scheduled as distinct event streams.
//! Equal timestamps always process controls, then arrivals, then recovery
//! polls, then render callbacks.

use core::fmt;
use core::num::NonZeroU64;

use rlb_clock::MonotonicInstant;
use rlb_codec::WireCodec;
use rlb_jitter::{
    GapKind, JitterBuffer, JitterError, JitterMetrics, PlayoutGeneration, PlayoutState,
    RenderReport, TargetMode,
};
use rlb_media::{
    AssemblerMetrics, AssemblyError, AssemblyOutcome, EpochEndRecord, FragmentAssembler, GapReason,
    GapRecord, MediaFragment, MediaIdentity, NackCandidate, NackPlannerConfig, PacketError,
    ParseContext, ParsedDatagram, parse_datagram,
};
use rlb_model::{MEDIA_UNIT_FRAMES, SourceId};

const MAX_SOURCES: usize = 62;

/// Nanosecond-domain deterministic simulation timestamp.
#[derive(Clone, Copy, Debug, Default, Eq, Hash, Ord, PartialEq, PartialOrd)]
#[repr(transparent)]
pub struct SimTime(u64);

impl SimTime {
    /// Creates a timestamp from nanoseconds since simulation start.
    #[must_use]
    pub const fn from_ns(nanoseconds: u64) -> Self {
        Self(nanoseconds)
    }

    /// Creates a timestamp from integer milliseconds.
    #[must_use]
    pub const fn from_ms(milliseconds: u64) -> Self {
        Self(milliseconds.saturating_mul(1_000_000))
    }

    /// Returns nanoseconds since simulation start.
    #[must_use]
    pub const fn as_ns(self) -> u64 {
        self.0
    }

    const fn instant(self) -> MonotonicInstant {
        MonotonicInstant::from_ticks(self.0)
    }
}

/// One canonical source truth record, independent of network arrivals.
#[derive(Clone, Debug, PartialEq)]
pub enum TruthRecord {
    /// Exact source samples for a complete 480-frame MEDIA unit.
    Media {
        /// Stable source.
        source_id: SourceId,
        /// Epoch record sequence.
        sequence: u32,
        /// Inclusive source sample start.
        start_sample: u64,
        /// Interleaved canonical samples.
        samples: Box<[f32]>,
    },
    /// Sender-declared source-time gap.
    Gap {
        /// Stable source.
        source_id: SourceId,
        /// Epoch record sequence.
        sequence: u32,
        /// Inclusive source sample start.
        start_sample: u64,
        /// Positive source-frame duration.
        frame_count: u32,
        /// Stable sender reason.
        reason: GapReason,
    },
    /// Exclusive source timeline end.
    EpochEnd {
        /// Stable source.
        source_id: SourceId,
        /// Exclusive source sample end.
        final_sample: u64,
    },
}

/// One active simulated receiver source.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SimSourceConfig {
    /// Exact active wire identity.
    pub identity: MediaIdentity,
    /// Active epoch codec.
    pub codec: WireCodec,
    /// One or two channels.
    pub channels: u8,
    /// Initial playout target mode.
    pub target_mode: TargetMode,
}

/// Observable result of one scheduled datagram.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ArrivalDisposition {
    /// Fragment remains incomplete.
    FragmentStored,
    /// Fragment was accepted behind a newer fragment key.
    FragmentReordered,
    /// Byte-identical fragment was ignored.
    DuplicateFragment,
    /// Complete unit decoded and entered the sample timeline.
    UnitComplete,
    /// Complete repair arrived behind the read cursor.
    LateFragment,
    /// Fragment exceeded the independent logical window.
    CapacityDropped,
    /// GAP entered the source timeline.
    GapInserted,
    /// EPOCH_END entered the source timeline.
    EpochEnded,
}

/// Recorded datagram disposition.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ArrivalLog {
    /// Event timestamp.
    pub time: SimTime,
    /// Routed source.
    pub source_id: SourceId,
    /// Deterministic result.
    pub disposition: ArrivalDisposition,
}

/// Recorded NACK planning result.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RecoveryLog {
    /// Poll timestamp.
    pub time: SimTime,
    /// Routed source.
    pub source_id: SourceId,
    /// Candidate generated by the media assembler.
    pub candidate: NackCandidate,
}

/// One source's report during a shared render callback.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct SourceRenderLog {
    /// Stable source.
    pub source_id: SourceId,
    /// Allocation-free jitter result.
    pub report: RenderReport,
}

/// Shared callback record. Source entries occupy the following contiguous
/// range in [`DeterministicSimulator::source_render_log`].
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RenderLog {
    /// Callback-entry timestamp.
    pub time: SimTime,
    /// Requested shared output frames.
    pub frames: u32,
    /// First source report index.
    pub source_log_start: usize,
    /// Number of independent source reports.
    pub source_log_count: usize,
}

/// Closed simulator failure set.
#[derive(Debug)]
pub enum SimError {
    /// Source table reached the first-release maximum.
    SourceCapacity,
    /// A stable source was configured twice.
    DuplicateSource(SourceId),
    /// An event routed to an unknown source.
    UnknownSource(SourceId),
    /// Event time moved behind an already executed event.
    TimeRegression {
        /// Last executed timestamp.
        previous: SimTime,
        /// Rejected event timestamp.
        current: SimTime,
    },
    /// Parsed identity differed from the routed active source.
    IdentityMismatch,
    /// Receiver simulation does not process inbound NACK requests.
    UnexpectedNack,
    /// Strict wire parser rejection.
    Packet(PacketError),
    /// Bounded fragment assembler failure.
    Assembly(AssemblyError),
    /// Sample timeline or render failure.
    Jitter(JitterError),
}

impl fmt::Display for SimError {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::SourceCapacity => formatter.write_str("simulator source capacity exceeded"),
            Self::DuplicateSource(source_id) => write!(formatter, "duplicate source {source_id}"),
            Self::UnknownSource(source_id) => write!(formatter, "unknown source {source_id}"),
            Self::TimeRegression { previous, current } => write!(
                formatter,
                "event time {} preceded executed time {}",
                current.0, previous.0
            ),
            Self::IdentityMismatch => formatter.write_str("routed media identity mismatch"),
            Self::UnexpectedNack => formatter.write_str("receiver received an unexpected NACK"),
            Self::Packet(error) => write!(formatter, "packet error: {error}"),
            Self::Assembly(error) => write!(formatter, "assembly error: {error}"),
            Self::Jitter(error) => write!(formatter, "jitter error: {error}"),
        }
    }
}

impl std::error::Error for SimError {}

impl From<PacketError> for SimError {
    fn from(error: PacketError) -> Self {
        Self::Packet(error)
    }
}

impl From<AssemblyError> for SimError {
    fn from(error: AssemblyError) -> Self {
        Self::Assembly(error)
    }
}

impl From<JitterError> for SimError {
    fn from(error: JitterError) -> Self {
        Self::Jitter(error)
    }
}

struct SourceRuntime {
    config: SimSourceConfig,
    assembler: FragmentAssembler,
    jitter: JitterBuffer,
    generation: PlayoutGeneration,
    decoded: Box<[f32]>,
    output: Vec<f32>,
}

impl SourceRuntime {
    fn new(config: SimSourceConfig) -> Result<Self, SimError> {
        let mut jitter = JitterBuffer::new(
            config.channels,
            config.target_mode,
            NonZeroU64::new(1_000_000_000).expect("nanosecond frequency"),
        )?;
        let generation = jitter.enable();
        Ok(Self {
            config,
            assembler: FragmentAssembler::new(
                config.identity,
                NackPlannerConfig::default().nanosecond_domain(),
            ),
            jitter,
            generation,
            decoded: vec![0.0; usize::from(MEDIA_UNIT_FRAMES) * usize::from(config.channels)]
                .into_boxed_slice(),
            output: Vec::new(),
        })
    }

    fn enable_generation(&mut self) {
        self.assembler = FragmentAssembler::new(
            self.config.identity,
            NackPlannerConfig::default().nanosecond_domain(),
        );
        self.generation = self.jitter.enable();
    }
}

#[derive(Debug)]
enum EventKind {
    Enable(SourceId),
    Disable(SourceId),
    Arrival {
        source_id: SourceId,
        bytes: Box<[u8]>,
    },
    PollRecovery {
        source_id: SourceId,
        deadline: SimTime,
    },
    Drift {
        source_id: SourceId,
        delta_source_frames: u64,
        delta_render_frames: u64,
    },
    Render(u32),
}

impl EventKind {
    const fn priority(&self) -> u8 {
        match self {
            Self::Enable(_) | Self::Disable(_) | Self::Drift { .. } => 0,
            Self::Arrival { .. } => 1,
            Self::PollRecovery { .. } => 2,
            Self::Render(_) => 3,
        }
    }
}

#[derive(Debug)]
struct Event {
    time: SimTime,
    serial: u64,
    kind: EventKind,
}

/// Deterministic, single-threaded arithmetic oracle for arrival and render.
#[derive(Default)]
pub struct DeterministicSimulator {
    sources: Vec<SourceRuntime>,
    truth: Vec<TruthRecord>,
    events: Vec<Event>,
    next_serial: u64,
    executed_through: Option<SimTime>,
    arrivals: Vec<ArrivalLog>,
    recovery: Vec<RecoveryLog>,
    renders: Vec<RenderLog>,
    source_renders: Vec<SourceRenderLog>,
}

impl DeterministicSimulator {
    /// Creates an empty simulation.
    #[must_use]
    pub const fn new() -> Self {
        Self {
            sources: Vec::new(),
            truth: Vec::new(),
            events: Vec::new(),
            next_serial: 0,
            executed_through: None,
            arrivals: Vec::new(),
            recovery: Vec::new(),
            renders: Vec::new(),
            source_renders: Vec::new(),
        }
    }

    /// Adds one independent active source and creates its first generation.
    pub fn add_source(&mut self, config: SimSourceConfig) -> Result<(), SimError> {
        if self.sources.len() >= MAX_SOURCES {
            return Err(SimError::SourceCapacity);
        }
        if self
            .sources
            .iter()
            .any(|source| source.config.identity.source_id == config.identity.source_id)
        {
            return Err(SimError::DuplicateSource(config.identity.source_id));
        }
        self.sources.push(SourceRuntime::new(config)?);
        Ok(())
    }

    /// Adds immutable canonical source truth without scheduling an arrival.
    pub fn add_truth(&mut self, record: TruthRecord) {
        self.truth.push(record);
    }

    /// Schedules an owned network datagram.
    pub fn schedule_arrival(
        &mut self,
        time: SimTime,
        source_id: SourceId,
        bytes: impl Into<Box<[u8]>>,
    ) {
        self.schedule(
            time,
            EventKind::Arrival {
                source_id,
                bytes: bytes.into(),
            },
        );
    }

    /// Schedules one recovery-budget evaluation.
    pub fn schedule_recovery_poll(
        &mut self,
        time: SimTime,
        source_id: SourceId,
        predicted_deadline: SimTime,
    ) {
        self.schedule(
            time,
            EventKind::PollRecovery {
                source_id,
                deadline: predicted_deadline,
            },
        );
    }

    /// Schedules a shared render callback for every configured source.
    pub fn schedule_render(&mut self, time: SimTime, frames: u32) {
        self.schedule(time, EventKind::Render(frames));
    }

    /// Invalidates one source's local playout generation.
    pub fn schedule_disable(&mut self, time: SimTime, source_id: SourceId) {
        self.schedule(time, EventKind::Disable(source_id));
    }

    /// Creates a fresh local playout generation with the same sender epoch.
    pub fn schedule_enable(&mut self, time: SimTime, source_id: SourceId) {
        self.schedule(time, EventKind::Enable(source_id));
    }

    /// Schedules one valid per-second source drift observation.
    pub fn schedule_drift_observation(
        &mut self,
        time: SimTime,
        source_id: SourceId,
        delta_source_frames: u64,
        delta_render_frames: u64,
    ) {
        self.schedule(
            time,
            EventKind::Drift {
                source_id,
                delta_source_frames,
                delta_render_frames,
            },
        );
    }

    /// Executes all pending events in deterministic order.
    pub fn run(&mut self) -> Result<(), SimError> {
        let mut events = core::mem::take(&mut self.events);
        events.sort_by_key(|event| (event.time, event.kind.priority(), event.serial));
        for event in events {
            if let Some(previous) = self.executed_through
                && event.time < previous
            {
                return Err(SimError::TimeRegression {
                    previous,
                    current: event.time,
                });
            }
            self.execute(event.time, event.kind)?;
            self.executed_through = Some(event.time);
        }
        Ok(())
    }

    /// Returns canonical source truth in insertion order.
    #[must_use]
    pub fn truth(&self) -> &[TruthRecord] {
        &self.truth
    }

    /// Returns datagram dispositions in execution order.
    #[must_use]
    pub fn arrival_log(&self) -> &[ArrivalLog] {
        &self.arrivals
    }

    /// Returns planned recovery requests.
    #[must_use]
    pub fn recovery_log(&self) -> &[RecoveryLog] {
        &self.recovery
    }

    /// Returns shared callback records.
    #[must_use]
    pub fn render_log(&self) -> &[RenderLog] {
        &self.renders
    }

    /// Returns per-source callback records referenced by [`RenderLog`].
    #[must_use]
    pub fn source_render_log(&self) -> &[SourceRenderLog] {
        &self.source_renders
    }

    /// Returns every interleaved output sample produced for one source.
    #[must_use]
    pub fn source_output(&self, source_id: SourceId) -> Option<&[f32]> {
        self.source(source_id)
            .map(|source| source.output.as_slice())
    }

    /// Returns one source's current jitter metrics.
    #[must_use]
    pub fn jitter_metrics(&self, source_id: SourceId) -> Option<JitterMetrics> {
        self.source(source_id).map(|source| source.jitter.metrics())
    }

    /// Returns one source's current assembler metrics.
    #[must_use]
    pub fn assembler_metrics(&self, source_id: SourceId) -> Option<AssemblerMetrics> {
        self.source(source_id)
            .map(|source| source.assembler.metrics())
    }

    /// Returns one source's current playout state.
    #[must_use]
    pub fn source_state(&self, source_id: SourceId) -> Option<PlayoutState> {
        self.source(source_id).map(|source| source.jitter.state())
    }

    /// Returns one source's local generation.
    #[must_use]
    pub fn source_generation(&self, source_id: SourceId) -> Option<PlayoutGeneration> {
        self.source(source_id).map(|source| source.generation)
    }

    /// Returns the ideal signed sample-slip count for a fixed-rate trace.
    ///
    /// This arithmetic oracle gives exactly 69,120 slips for two hours at
    /// ±200 ppm and 48 kHz.
    #[must_use]
    pub fn ideal_drift_slips(render_frames: u64, drift_ppm: i32) -> i64 {
        let signed_frames = i128::from(render_frames) * i128::from(drift_ppm);
        let slips = signed_frames / 1_000_000;
        slips.clamp(i128::from(i64::MIN), i128::from(i64::MAX)) as i64
    }

    fn schedule(&mut self, time: SimTime, kind: EventKind) {
        let serial = self.next_serial;
        self.next_serial = self.next_serial.wrapping_add(1);
        self.events.push(Event { time, serial, kind });
    }

    fn execute(&mut self, time: SimTime, kind: EventKind) -> Result<(), SimError> {
        match kind {
            EventKind::Enable(source_id) => self.source_mut(source_id)?.enable_generation(),
            EventKind::Disable(source_id) => self.source_mut(source_id)?.jitter.disable(),
            EventKind::Drift {
                source_id,
                delta_source_frames,
                delta_render_frames,
            } => self
                .source_mut(source_id)?
                .jitter
                .observe_drift(delta_source_frames, delta_render_frames),
            EventKind::Arrival { source_id, bytes } => {
                self.execute_arrival(time, source_id, &bytes)?;
            }
            EventKind::PollRecovery {
                source_id,
                deadline,
            } => {
                let source = self.source_mut(source_id)?;
                let mut candidates = [NackCandidate::default(); 26];
                let count = source
                    .assembler
                    .poll_nacks(time.instant(), &mut candidates, |_| {
                        Some(deadline.instant())
                    });
                for candidate in candidates.into_iter().take(count) {
                    self.recovery.push(RecoveryLog {
                        time,
                        source_id,
                        candidate,
                    });
                }
            }
            EventKind::Render(frames) => self.execute_render(time, frames)?,
        }
        Ok(())
    }

    fn execute_arrival(
        &mut self,
        time: SimTime,
        source_id: SourceId,
        bytes: &[u8],
    ) -> Result<(), SimError> {
        let source = self.source_mut(source_id)?;
        let parsed = parse_datagram(
            bytes,
            ParseContext {
                expected_room_id: Some(source.config.identity.room_id),
                expected_sender_member_id: Some(source.config.identity.sender_member_id),
                expected_sender_run_id: Some(source.config.identity.sender_run_id),
                expected_source_id: Some(source.config.identity.source_id),
                expected_stream_epoch: Some(source.config.identity.stream_epoch),
                subscription_allowed: Some(true),
                expected_channels: Some(source.config.channels),
                expected_codec: Some(source.config.codec),
            },
        )?;
        let identity = match parsed {
            ParsedDatagram::Media(MediaFragment { header, .. }) => header.identity,
            ParsedDatagram::Gap(GapRecord { identity, .. })
            | ParsedDatagram::EpochEnd(EpochEndRecord { identity, .. }) => identity,
            ParsedDatagram::Nack(_) => return Err(SimError::UnexpectedNack),
        };
        if identity != source.config.identity {
            return Err(SimError::IdentityMismatch);
        }
        if let Some(cursor) = source.jitter.read_cursor() {
            source.assembler.set_read_cursor(cursor);
        }
        let disposition = match parsed {
            ParsedDatagram::Media(fragment) => {
                match source
                    .assembler
                    .push(fragment, time.instant(), &mut source.decoded)?
                {
                    AssemblyOutcome::Stored => ArrivalDisposition::FragmentStored,
                    AssemblyOutcome::Reordered => ArrivalDisposition::FragmentReordered,
                    AssemblyOutcome::Duplicate => ArrivalDisposition::DuplicateFragment,
                    AssemblyOutcome::Late => ArrivalDisposition::LateFragment,
                    AssemblyOutcome::CapacityDropped => ArrivalDisposition::CapacityDropped,
                    AssemblyOutcome::Complete(unit) => {
                        let insertion = source.jitter.insert_media_with_recovery(
                            source.generation,
                            unit.unit_sequence,
                            unit.start_sample,
                            &source.decoded,
                            time.instant(),
                            unit.recovered_after_nack,
                        )?;
                        match insertion {
                            rlb_jitter::InsertOutcome::Inserted
                            | rlb_jitter::InsertOutcome::Reordered => {
                                if let Some(cursor) = source.jitter.read_cursor() {
                                    source.assembler.set_preroll_anchor(cursor);
                                }
                                ArrivalDisposition::UnitComplete
                            }
                            rlb_jitter::InsertOutcome::Late
                            | rlb_jitter::InsertOutcome::Stale
                            | rlb_jitter::InsertOutcome::StaleGeneration => {
                                ArrivalDisposition::LateFragment
                            }
                            rlb_jitter::InsertOutcome::CapacityDropped => {
                                ArrivalDisposition::CapacityDropped
                            }
                            rlb_jitter::InsertOutcome::Duplicate => {
                                ArrivalDisposition::DuplicateFragment
                            }
                        }
                    }
                }
            }
            ParsedDatagram::Gap(record) => {
                source.jitter.insert_gap(
                    source.generation,
                    record.record_sequence,
                    record.start_sample,
                    record.frame_count,
                    map_gap_reason(record.reason),
                )?;
                ArrivalDisposition::GapInserted
            }
            ParsedDatagram::EpochEnd(record) => {
                source.jitter.insert_epoch_end(
                    source.generation,
                    record.next_record_sequence,
                    record.final_sample,
                )?;
                ArrivalDisposition::EpochEnded
            }
            ParsedDatagram::Nack(_) => return Err(SimError::UnexpectedNack),
        };
        self.arrivals.push(ArrivalLog {
            time,
            source_id,
            disposition,
        });
        Ok(())
    }

    fn execute_render(&mut self, time: SimTime, frames: u32) -> Result<(), SimError> {
        let start = self.source_renders.len();
        for source in &mut self.sources {
            source
                .jitter
                .note_render_callback_entry(time.instant(), frames);
        }
        for source in &mut self.sources {
            let sample_count = usize::try_from(frames)
                .unwrap_or(usize::MAX)
                .saturating_mul(usize::from(source.config.channels));
            let output_start = source.output.len();
            source.output.resize(output_start + sample_count, 0.0);
            let report =
                source
                    .jitter
                    .render(time.instant(), frames, &mut source.output[output_start..])?;
            if let Some(cursor) = source.jitter.read_cursor() {
                source.assembler.set_read_cursor(cursor);
            }
            self.source_renders.push(SourceRenderLog {
                source_id: source.config.identity.source_id,
                report,
            });
        }
        self.renders.push(RenderLog {
            time,
            frames,
            source_log_start: start,
            source_log_count: self.sources.len(),
        });
        Ok(())
    }

    fn source(&self, source_id: SourceId) -> Option<&SourceRuntime> {
        self.sources
            .iter()
            .find(|source| source.config.identity.source_id == source_id)
    }

    fn source_mut(&mut self, source_id: SourceId) -> Result<&mut SourceRuntime, SimError> {
        self.sources
            .iter_mut()
            .find(|source| source.config.identity.source_id == source_id)
            .ok_or(SimError::UnknownSource(source_id))
    }
}

fn map_gap_reason(reason: GapReason) -> GapKind {
    match reason {
        GapReason::CaptureOverrun => GapKind::CaptureOverrun,
        GapReason::SendQueueOverflow => GapKind::SendQueueOverflow,
        GapReason::SendDeadlineDrop => GapKind::SendDeadlineDrop,
        GapReason::KnownAdapterGap => GapKind::KnownAdapterGap,
    }
}

